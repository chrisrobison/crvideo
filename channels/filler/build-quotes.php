<?php
declare(strict_types=1);

// Rebuilds channels/filler/quotes.json, the deck of one-liners the player
// shows over filler video (see channels/filler.js), from two plain-text
// sources on cdr2.com:
//
//   https://cdr2.com/data/quotes.txt                  QuoteID|Quote|Author|Views|Votes
//   https://cdr2.com/data/imponderablequestions.htm   one <li> per question
//
// Usage: php channels/filler/build-quotes.php [quotes-source] [imponderables-source]
//   Either source may be a local path instead of a URL.
//
// Output is a snapshot (the player never fetches cdr2.com at runtime). A
// station is on the air for every age, so lines that are crude, morbid, or
// about drink/drugs/sex are dropped by a keyword screen; tweak BLOCKED and
// re-run, then eyeball the diff.

const QUOTES_SRC = 'https://cdr2.com/data/quotes.txt';
const IMPONDERABLES_SRC = 'https://cdr2.com/data/imponderablequestions.htm';
const MAX_LENGTH = 180; // longer lines don't fit a filler card legibly

const BLOCKED = [
    'sex', 'naked', 'nude', 'women', 'woman', 'wife', 'wives', 'girl', 'whore', 'slut', 'bra ', 'panties',
    'hemorrhoid', 'drunk', 'beer', 'wine', 'whiskey', 'liquor', 'alcohol', 'bottle', 'booze', 'smok',
    'cigar', 'drug', 'marijuana', 'pot ', 'kill', 'murder', 'suicide', 'die ', 'died', 'dies ', 'dead', 'death',
    'lethal', 'shoot', 'gun', 'rape', 'hell', 'damn', 'ass ', 'crap', 'shit', 'fuck', 'bitch', 'penis',
    'breast', 'tuberculosis', 'cancer', 'virgin', 'pregnan', 'divorce', 'prostitut', 'lust', 'adulter',
    'bathroom', 'toilet', 'fart', 'poop', 'urine', 'pee ', 'sperm', 'orgasm', 'condom', 'racis', 'nigg', 'kamikaze', 'unconscious', 'aborigin', 'acid', 'castrat', 'cannibal', 'drown', 'choke', 'plane crash', 'deaf', 'dyslexia', 'lingerie', 'stun', 'bomber', 'sritched',
];

function fetchText(string $src): string
{
    $ctx = stream_context_create(['http' => ['timeout' => 20, 'user_agent' => 'crvideo-filler-build']]);
    $text = @file_get_contents($src, false, $ctx);
    if ($text === false) {
        fwrite(STDERR, "Could not read $src\n");
        exit(1);
    }
    // The sources are windows-1252/ASCII; normalize to UTF-8 for the JSON.
    return mb_check_encoding($text, 'UTF-8') ? $text : mb_convert_encoding($text, 'UTF-8', 'Windows-1252');
}

function clean(string $s): string
{
    $s = html_entity_decode(strip_tags($s), ENT_QUOTES | ENT_HTML5, 'UTF-8');
    return trim(preg_replace('/\s+/u', ' ', $s));
}

function allowed(string $line, int $minLength = 12): bool
{
    // A blocked word matches at the start of a word (so "kill" catches
    // "killing" but not "skill", "hell" not "shell"); a trailing space in
    // the entry also pins the end ("die " catches "die," but not "diet").
    foreach (BLOCKED as $word) {
        $end = str_ends_with($word, ' ') ? '\\b' : '';
        if (preg_match('/\\b' . preg_quote(trim($word), '/') . $end . '/i', $line)) {
            return false;
        }
    }
    return mb_strlen($line) <= MAX_LENGTH && mb_strlen($line) >= $minLength;
}

$out = ['quote' => [], 'imponderable' => []];
$seen = [];

foreach (preg_split('/\R/', fetchText($argv[1] ?? QUOTES_SRC)) as $i => $row) {
    if ($i === 0 || trim($row) === '') {
        continue; // header / blank
    }
    // QuoteID|Quote|Author|Views|Votes -- but a few quotes contain a literal
    // "|" themselves ("Life is like a diaper|short and loaded."). A second
    // field that starts lowercase continues the quote rather than naming
    // its author.
    $cols = explode('|', $row);
    $text = clean($cols[1] ?? '');
    $author = clean($cols[2] ?? '');
    if ($author !== '' && preg_match('/^\p{Ll}/u', $author)) {
        $text = rtrim($text, " .") . ' — ' . $author;
        $author = '';
    }
    $author = rtrim($author, ')');
    $key = strtolower($text);
    if ($text === '' || isset($seen[$key]) || !allowed($text) || ($author !== '' && !allowed($author, 0))) {
        continue;
    }
    $seen[$key] = true;
    $out['quote'][] = $author === '' ? ['text' => $text] : ['text' => $text, 'author' => $author];
}

preg_match_all('/<li>(.*?)<\/li>/is', fetchText($argv[2] ?? IMPONDERABLES_SRC), $m);
foreach ($m[1] as $li) {
    $text = clean($li);
    $key = strtolower($text);
    if ($text === '' || isset($seen[$key]) || !allowed($text)) {
        continue;
    }
    $seen[$key] = true;
    $out['imponderable'][] = ['text' => $text];
}

$doc = [
    '_note' => 'Generated by channels/filler/build-quotes.php from cdr2.com/data/quotes.txt and imponderablequestions.htm. Do not hand-edit; re-run the script.',
    'schema_version' => 1,
    'quotes' => $out['quote'],
    'imponderables' => $out['imponderable'],
];
file_put_contents(__DIR__ . '/quotes.json', json_encode($doc, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n");
printf("quotes: %d, imponderables: %d\n", count($out['quote']), count($out['imponderable']));
